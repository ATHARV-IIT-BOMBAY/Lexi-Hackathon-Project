import React from 'react';
import { generateTracingStrokes } from '../utils/VectorEngine';

export default function PrintableWorksheet({ history, user }) {
  if (!user) return null;

  const targetScores = {};
  history.forEach(item => {
    if (item.mode === 'letters' || item.mode === 'words') {
      const target = String(item.target || item.mission).split(' ')[0];
      if (target && target.length > 0) {
        if (!targetScores[target]) targetScores[target] = [];
        targetScores[target].push(item.score);
      }
    }
  });

  const avgScores = Object.entries(targetScores).map(([target, scores]) => ({
    target,
    avg: scores.reduce((a, b) => a + b, 0) / scores.length
  }));

  avgScores.sort((a, b) => a.avg - b.avg);
  
  let practiceTargets = avgScores.slice(0, 3).map(x => x.target);
  
  if (practiceTargets.length === 0) {
    practiceTargets = ['A', 'B', 'C'];
  } else {
    while (practiceTargets.length < 3) {
      practiceTargets.push(practiceTargets[0]);
    }
  }

  return (
    <div className="printable-worksheet" style={{ width: '100%', height: '100%', background: 'white' }}>
      <div style={{ display: 'flex', justifyContent: 'space-between', marginBottom: '40px' }}>
        <h1 style={{ margin: 0, color: '#334155' }}>Lexi Practice Sheet</h1>
        <h2 style={{ margin: 0, color: '#64748b' }}>Name: {user.name}</h2>
      </div>

      <svg width="100%" height="900" viewBox="0 0 800 900">
        {practiceTargets.map((target, idx) => {
          const startY = 100 + (idx * 250);
          const copies = 3;
          const spacing = 800 / copies;
          const allStrokes = [];
          
          for (let i = 0; i < copies; i++) {
            const centerX = (spacing / 2) + (i * spacing);
            const strokes = generateTracingStrokes(target, centerX, startY + 50, 100);
            allStrokes.push(...strokes);
          }

          return (
            <g key={idx}>
              <line x1="0" y1={startY + 100} x2="800" y2={startY + 100} stroke="#94a3b8" strokeWidth="2" />
              <line x1="0" y1={startY + 50} x2="800" y2={startY + 50} stroke="#cbd5e1" strokeWidth="2" strokeDasharray="10,10" />
              <line x1="0" y1={startY} x2="800" y2={startY} stroke="#94a3b8" strokeWidth="2" />

              <line x1="0" y1={startY + 200} x2="800" y2={startY + 200} stroke="#94a3b8" strokeWidth="2" />
              <line x1="0" y1={startY + 150} x2="800" y2={startY + 150} stroke="#cbd5e1" strokeWidth="2" strokeDasharray="10,10" />
              <line x1="0" y1={startY + 100} x2="800" y2={startY + 100} stroke="#94a3b8" strokeWidth="2" />

              {allStrokes.map((stroke, sIdx) => (
                <polyline
                  key={sIdx}
                  points={stroke.points.map(p => `${p.x},${p.y}`).join(' ')}
                  fill="none"
                  stroke="#94a3b8"
                  strokeWidth="3"
                  strokeDasharray="4,8"
                  strokeLinecap="round"
                  strokeLinejoin="round"
                />
              ))}
            </g>
          );
        })}
      </svg>
      <div style={{ marginTop: '20px', textAlign: 'center', color: '#94a3b8', fontSize: '0.9rem' }}>
        Generated by Lexi AI ✨ — Practice makes progress!
      </div>
    </div>
  );
}
